  private async attachImageFromDiskPath(path: string): Promise<boolean> {
    try {
      const imported = await api.importImagePath(path);
      const name = path.split(/[/\\]/).pop() || "image.png";
      const mime = /\.jpe?g$/i.test(name)
        ? "image/jpeg"
        : /\.webp$/i.test(name)
          ? "image/webp"
          : /\.gif$/i.test(name)
            ? "image/gif"
            : "image/png";
      try {
        const { convertFileSrc } = await import("@tauri-apps/api/core");
        const res = await fetch(convertFileSrc(imported));
        const blob = await res.blob();
        const file = new File([blob], name, { type: mime });
        this.addComposerAttachment(imported, file);
      } catch {
        this.addComposerAttachment(imported);
      }
      return true;
    } catch (err) {
      console.error(err);
      return false;
    }
  }

  private async attachImageFiles(files: File[]) {
    let ok = 0;
    for (const file of files) {
      try {
        const path = await this.persistImageFile(file);
        if (!path) continue;
        this.addComposerAttachment(path, file);
        ok += 1;
      } catch (err) {
        console.error(err);
      }
    }
    if (!ok) {
      const toast = document.getElementById("toast");
      if (toast) {
        toast.textContent = "Could not paste image";
        toast.hidden = false;
        window.setTimeout(() => {
          toast.hidden = true;
        }, 4000);
      }
    }
  }

  private async persistImageFile(file: File): Promise<string | null> {
    const buf = new Uint8Array(await file.arrayBuffer());
    if (!buf.length) return null;
    let binary = "";
    const chunk = 0x8000;
    for (let i = 0; i < buf.length; i += chunk) {
      binary += String.fromCharCode(...buf.subarray(i, i + chunk));
    }
    const dataBase64 = btoa(binary);
    return api.savePastedImage(dataBase64, file.type || "image/png");
  }

