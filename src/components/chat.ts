  private isImageFile(file: File): boolean {
    if (file.type && file.type.startsWith("image/") && !file.type.includes("svg")) return true;
    return this.isImagePath(file.name || "");
  }

  private isImagePath(path: string): boolean {
    return /\.(png|jpe?g|gif|webp|bmp)$/i.test(path);
  }

  private isVideoPath(path: string): boolean {
    return /\.(mp4|mov|m4v|webm|mkv|avi|wmv|flv|mpeg|mpg|3gp)$/i.test(path);
  }

  private isVideoFile(file: File): boolean {
    return Boolean(file.type?.toLowerCase().startsWith("video/")) || this.isVideoPath(file.name || "");
  }

  private videoExtensionForFile(file: File): string | null {
    const named = file.name.match(/\.([A-Za-z0-9]+)$/)?.[1]?.toLowerCase() || "";
    if (named && this.isVideoPath(`file.${named}`)) return named;
    const mime = (file.type || "").toLowerCase().split(";", 1)[0];
    const byMime: Record<string, string> = {
      "video/mp4": "mp4",
      "video/quicktime": "mov",
      "video/webm": "webm",
      "video/x-matroska": "mkv",
      "video/x-msvideo": "avi",
      "video/x-ms-wmv": "wmv",
      "video/x-flv": "flv",
      "video/mpeg": "mpeg",
      "video/3gpp": "3gp",
    };
    return byMime[mime] || null;
  }

  private pathFromClipboardText(raw: string): string | null {
    let text = String(raw || "").trim().replace(/^<|>$/g, "");
    if (!text || text.startsWith("#")) return null;
    if (text.toLowerCase().startsWith("file:///")) {
      try {
        text = decodeURIComponent(text.slice("file:///".length));
        if (/^[A-Za-z]:\//.test(text)) text = text.replace(/\//g, "\\");
      } catch {
        return null;
      }
    }
    // Windows absolute path or quoted path from Explorer.
    text = text.replace(/^"(.*)"$/, "$1");
    if (!/^[A-Za-z]:[\\/]/.test(text) && !text.startsWith("\\\\")) return null;
    if (!this.isImagePath(text) && !this.isVideoPath(text)) return null;
    return text;
  }

  /**
   * WebView clipboard File objects normally expose only bytes, but Windows
   * Explorer can provide an absolute disk path as a non-standard property.
   * Prefer it whenever available: native import keeps large videos off the
   * JavaScript heap and applies the same type/size validation as + → Video.
   */
  private pathFromClipboardFile(file: File): string | null {
    const candidate = (file as File & { path?: unknown }).path;
    return typeof candidate === "string" ? this.pathFromClipboardText(candidate) : null;
  }

  private async handleComposerPaste(e: ClipboardEvent) {
    const cd = e.clipboardData;
    if (!cd) return;

    const imageFiles: File[] = [];
    const videoFiles: File[] = [];
    const filePaths: string[] = [];
    const inspectFile = (file: File) => {
      const path = this.pathFromClipboardFile(file);
      if (path) {
        filePaths.push(path);
      } else if (this.isVideoFile(file)) {
        videoFiles.push(file);
      } else if (this.isImageFile(file)) {
        imageFiles.push(file);
      }
    };
    if (cd.files?.length) {
      for (const file of Array.from(cd.files)) {
        inspectFile(file);
      }
    }
    if (!cd.files?.length && cd.items?.length) {
      for (const item of Array.from(cd.items)) {
        if (item.kind !== "file") continue;
        const file = item.getAsFile();
        if (file) inspectFile(file);
      }
    }

    // Explorer "Copy" often puts paths/URIs rather than media bytes. This
    // handles one or many copied videos using the secure native import path.
    const uriList = cd.getData("text/uri-list") || "";
    const plain = cd.getData("text/plain") || "";
    const candidates = [...uriList.split(/\r?\n/), ...plain.split(/\r?\n/)]
      .map((line) => line.trim())
      .filter(Boolean);
    const pathCandidates = [
      ...filePaths,
      ...candidates
        .map((candidate) => this.pathFromClipboardText(candidate))
        .filter((path): path is string => Boolean(path)),
    ];
    const seenPaths = new Set<string>();
    const paths = pathCandidates.filter((path) => {
      const identity = path.toLowerCase();
      if (seenPaths.has(identity)) return false;
      seenPaths.add(identity);
      return true;
    });
    // Preserve the existing byte-paste behavior for images: some WebViews
    // expose both image bytes and a matching URI for one clipboard item.
    const imagePaths = imageFiles.length ? [] : paths.filter((path) => this.isImagePath(path));
    const videoPaths = paths.filter((path) => this.isVideoPath(path));
    const hasDomMedia = Boolean(
      imageFiles.length || imagePaths.length || videoFiles.length || videoPaths.length,
    );
    const claimsFiles = Array.from(cd.types || []).some((type) => type.toLowerCase() === "files");

    // Normal text paste must remain native and synchronous. A file clipboard
    // that WebView2 has hidden carries no usable DOM text, so it is safe to
    // suppress that empty default while the native CF_HDROP bridge checks it.
    if (!hasDomMedia && !claimsFiles && (uriList.trim() || plain.trim())) return;

    e.preventDefault();
    let nativeVideoPaths: string[] = [];
    let nativeErrors: string[] = [];
    if (!videoFiles.length && !videoPaths.length) {
      try {
        const imported = await api.importClipboardVideos();
        nativeVideoPaths = imported.paths;
        nativeErrors = imported.errors;
      } catch (error) {
        // Image bytes and explicit disk paths still work if another Windows
        // process briefly owns the clipboard. Only surface the error when the
        // native bridge was the sole possible source.
        console.error(error);
        if (!hasDomMedia) this.showAttachmentToast("Could not read copied video files");
      }
    }

    // Snipping Tool may expose a thumbnail image in the DOM alongside the
    // actual recording in CF_HDROP. Prefer the video in that case, but retain
    // explicit image paths from a genuine mixed Explorer selection.
    if (imageFiles.length && !nativeVideoPaths.length) await this.attachImageFiles(imageFiles);
    if (imagePaths.length) await this.attachImagePaths(imagePaths);
    if (videoFiles.length) await this.attachVideoFiles(videoFiles);
    if (videoPaths.length) await this.attachVideoPaths(videoPaths);
    for (const path of nativeVideoPaths) this.addComposerVideoAttachment(path);
    if (nativeErrors.length) {
      console.error("Could not import every copied video", nativeErrors);
      this.showAttachmentToast(
        nativeVideoPaths.length
          ? `${nativeErrors.length} copied video${nativeErrors.length === 1 ? "" : "s"} could not be attached`
          : nativeErrors[0],
      );
    }
  }

  private async handleComposerDrop(e: DragEvent) {
    const list = e.dataTransfer?.files;
    if (!list?.length) return;
    const files = Array.from(list).filter((f) => this.isImageFile(f));
    if (!files.length) return;
    e.preventDefault();
    await this.attachImageFiles(files);
  }

